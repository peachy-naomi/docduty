'use client';

import { useEffect, useState } from 'react';
import { useParams } from 'next/navigation';
import { verifyDocument } from '@/lib/api';

export default function VerifyInvoicePage() {
  const params = useParams();
  const id = Number(params.id);
  const [result, setResult] = useState<any>(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    verifyDocument('invoice', id)
      .then(setResult)
      .catch((err) => setError(err.response?.data?.detail || 'Verification failed'))
      .finally(() => setLoading(false));
  }, [id]);

  return (
    <main className="min-h-screen flex items-center justify-center px-4" style={{ background: '#FAFAFA' }}>
      <div className="card p-8 max-w-md w-full text-center">
        {loading && <p style={{ color: '#6B7280' }}>Verifying...</p>}

        {!loading && result && (
          <>
            <div className="w-14 h-14 rounded-full mx-auto mb-4 flex items-center justify-center" style={{ background: '#F3EFFD' }}>
              <svg className="w-6 h-6" fill="none" stroke="#059669" strokeWidth="2" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" d="M5 13l4 4L19 7" />
              </svg>
            </div>
            <h1 className="font-display text-xl font-bold mb-1" style={{ color: '#1A1A1A' }}>Document Verified</h1>
            <p className="text-sm mb-6" style={{ color: '#6B7280' }}>
              This is a genuine document generated by DocDuty.
            </p>
            <div className="text-left space-y-2 p-4 rounded-xl" style={{ background: '#F3EFFD' }}>
              <Row label="Reference" value={result.reference} />
              <Row label="Issued By" value={result.issued_by} />
              <Row label="Issued To" value={result.issued_to} />
              <Row label="Date" value={result.issue_date} />
              <Row label="Amount" value={`₦${result.amount_naira?.toLocaleString()}`} />
            </div>
          </>
        )}

        {!loading && error && (
          <>
            <div className="w-14 h-14 rounded-full mx-auto mb-4 flex items-center justify-center" style={{ background: '#FEE2E2' }}>
              <svg className="w-6 h-6" fill="none" stroke="#DC2626" strokeWidth="2" viewBox="0 0 24 24">
                <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
              </svg>
            </div>
            <h1 className="font-display text-xl font-bold mb-1" style={{ color: '#1A1A1A' }}>Could Not Verify</h1>
            <p className="text-sm" style={{ color: '#6B7280' }}>{error}</p>
          </>
        )}
      </div>
    </main>
  );
}

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex justify-between text-sm">
      <span style={{ color: '#6B7280' }}>{label}</span>
      <span style={{ color: '#1A1A1A' }} className="font-medium">{value}</span>
    </div>
  );
}
